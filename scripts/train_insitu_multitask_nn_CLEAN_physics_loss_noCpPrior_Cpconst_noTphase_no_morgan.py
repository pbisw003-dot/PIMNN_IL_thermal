def norm_text(x: object) -> str:
    if x is None or (isinstance(x, float) and np.isnan(x)):
        return ""
    return str(x).strip()


def first_existing(df: pd.DataFrame, names: Iterable[str]) -> Optional[str]:
    lower_map = {c.lower(): c for c in df.columns}
    for name in names:
        if name in df.columns:
            return name
        if name.lower() in lower_map:
            return lower_map[name.lower()]
    return None


def to_numeric_series(df: pd.DataFrame, col: str, default: float = np.nan) -> pd.Series:
    if col in df.columns:
        return pd.to_numeric(df[col], errors="coerce")
    return pd.Series(default, index=df.index, dtype=float)


def safe_div(a: np.ndarray | pd.Series | float, b: np.ndarray | pd.Series | float) -> np.ndarray:
    a = np.asarray(a, dtype=float)
    b = np.asarray(b, dtype=float)
    out = np.full(np.broadcast_shapes(a.shape, b.shape), np.nan, dtype=float)
    aa = np.broadcast_to(a, out.shape)
    bb = np.broadcast_to(b, out.shape)
    mask = np.isfinite(aa) & np.isfinite(bb) & (np.abs(bb) > 1e-12)
    out[mask] = aa[mask] / bb[mask]
    return out


def mol_from_smiles(smiles: object) -> Optional[Chem.Mol]:
    s = norm_text(smiles)
    if not s:
        return None
    try:
        mol = Chem.MolFromSmiles(s)
        return mol
    except Exception:
        return None


def formal_charge(mol: Optional[Chem.Mol]) -> float:
    if mol is None:
        return np.nan
    try:
        return float(sum(atom.GetFormalCharge() for atom in mol.GetAtoms()))
    except Exception:
        return np.nan


def atom_counts(mol: Optional[Chem.Mol]) -> Dict[str, float]:
    counts = {f"n_{el}": 0.0 for el in ELEMENTS}
    counts["n_H_total"] = 0.0
    counts["n_heavy_total"] = 0.0
    counts["n_halogen"] = 0.0
    counts["n_hetero_no_halogen"] = 0.0
    if mol is None:
        return {k: np.nan for k in counts}

    try:
        for atom in mol.GetAtoms():
            el = atom.GetSymbol()
            if el in ELEMENTS:
                counts[f"n_{el}"] += 1.0
            counts["n_H_total"] += float(atom.GetTotalNumHs())
            if el != "H":
                counts["n_heavy_total"] += 1.0
            if el in ["F", "Cl", "Br", "I"]:
                counts["n_halogen"] += 1.0
            if el not in ["C", "H", "F", "Cl", "Br", "I"]:
                counts["n_hetero_no_halogen"] += 1.0
    except Exception:
        return {k: np.nan for k in counts}
    return counts


