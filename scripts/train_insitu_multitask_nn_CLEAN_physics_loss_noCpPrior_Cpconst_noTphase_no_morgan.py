class ILPointDataset(Dataset):
    def __init__(self, row_df: pd.DataFrame, group_to_idx: Dict[str, int]):
        self.group_idx = np.array([group_to_idx[g] for g in row_df["group_id"].values], dtype=np.int64)
        self.T = pd.to_numeric(row_df["temperature_K"], errors="coerce").to_numpy(np.float32)
        self.rho = pd.to_numeric(row_df.get("density_kg_m3"), errors="coerce").to_numpy(np.float32)
        self.cp = pd.to_numeric(row_df.get("cp_JkgK"), errors="coerce").to_numpy(np.float32)
        if "log10_viscosity_mPa_s" in row_df.columns:
            self.logeta = pd.to_numeric(row_df["log10_viscosity_mPa_s"], errors="coerce").to_numpy(np.float32)
        else:
            eta = pd.to_numeric(row_df.get("viscosity_mPa_s"), errors="coerce").to_numpy(float)
            self.logeta = np.where(np.isfinite(eta) & (eta > 0), np.log10(eta), np.nan).astype(np.float32)

        self.rho_mask = np.isfinite(self.rho).astype(np.float32)
        self.cp_mask = np.isfinite(self.cp).astype(np.float32)
        self.eta_mask = np.isfinite(self.logeta).astype(np.float32)

        # Replace NaNs with zeros so tensors are finite; masks control losses.
        self.rho = np.where(np.isfinite(self.rho), self.rho, 0.0).astype(np.float32)
        self.cp = np.where(np.isfinite(self.cp), self.cp, 0.0).astype(np.float32)
        self.logeta = np.where(np.isfinite(self.logeta), self.logeta, 0.0).astype(np.float32)

    def __len__(self) -> int:
        return len(self.T)

    def __getitem__(self, idx: int):
        return {
            "group_idx": torch.tensor(self.group_idx[idx], dtype=torch.long),
            "T": torch.tensor(self.T[idx], dtype=torch.float32),
            "rho": torch.tensor(self.rho[idx], dtype=torch.float32),
            "cp": torch.tensor(self.cp[idx], dtype=torch.float32),
            "logeta": torch.tensor(self.logeta[idx], dtype=torch.float32),
            "rho_mask": torch.tensor(self.rho_mask[idx], dtype=torch.float32),
            "cp_mask": torch.tensor(self.cp_mask[idx], dtype=torch.float32),
            "eta_mask": torch.tensor(self.eta_mask[idx], dtype=torch.float32),
        }


class InSituILModel(nn.Module):
    def __init__(self, n_features: int, degree: int, hidden: List[int], dropout: float, scaling: Scaling, cp_prior_params: Dict[str, float]):
        super().__init__()
        self.degree = degree
        self.scaling = scaling
        self.cp_prior_params = cp_prior_params

        layers: List[nn.Module] = []
        prev = n_features
        for h in hidden:
            layers.append(nn.Linear(prev, h))
            layers.append(nn.ReLU())
            if dropout > 0:
                layers.append(nn.Dropout(dropout))
            prev = h
        self.shared = nn.Sequential(*layers)

        self.density_head = nn.Linear(prev, 2)          # scaled v0, scaled v1
        self.eta_head = nn.Linear(prev, degree + 1)     # scaled A, b1..bd
        self.cp_head = nn.Sequential(
            nn.Linear(prev + degree + 4, max(32, hidden[-1] // 2 if hidden else 64)),
            nn.ReLU(),
            nn.Dropout(dropout) if dropout > 0 else nn.Identity(),
            nn.Linear(max(32, hidden[-1] // 2 if hidden else 64), 1),
        )

        self._init_heads()

    def _init_heads(self) -> None:
        # Start density near invrho_scale * 1.0 with weak T-dependence.
        nn.init.zeros_(self.density_head.weight)
        nn.init.zeros_(self.density_head.bias)
        with torch.no_grad():
            self.density_head.bias[0] = 1.0  # v0_scaled
            self.density_head.bias[1] = 0.0  # v1_scaled per 100 K

        nn.init.zeros_(self.eta_head.weight)
        nn.init.zeros_(self.eta_head.bias)
        nn.init.zeros_(self.cp_head[-1].weight)
        nn.init.zeros_(self.cp_head[-1].bias)

    def forward(self, X_group: torch.Tensor, group_idx: torch.Tensor, T: torch.Tensor) -> Dict[str, torch.Tensor]:
        h = self.shared(X_group[group_idx])
        dcoef = self.density_head(h)
        ecoef = self.eta_head(h)

        Tref = self.scaling.tref
        dT_scaled = (T - Tref) / 100.0
        theta = Tref / torch.clamp(T, min=1.0)
        theta_powers = torch.stack([theta ** k for k in range(1, self.degree + 1)], dim=1)

        # Linear specific volume in scaled form:
        # invrho = invrho_scale * (v0_scaled + v1_scaled * ((T-Tref)/100)).
        v_scaled = dcoef[:, 0] + dcoef[:, 1] * dT_scaled
        v_scaled_clamped = torch.clamp(v_scaled, min=0.2, max=3.0)
        invrho_pred = self.scaling.invrho_scale * v_scaled_clamped
        rho_pred = 1.0 / torch.clamp(invrho_pred, min=1e-8)

        # Dimensionless inverse-temperature polynomial. The NN coefficients are
        # scaled by logeta_std and shifted by logeta_mean for numerical stability.
        eta_scaled = ecoef[:, 0] + torch.sum(ecoef[:, 1:] * theta_powers, dim=1)
        logeta_pred = self.scaling.logeta_mean + self.scaling.logeta_std * eta_scaled

        rho_scaled = rho_pred / 1000.0
        invrho_scaled = invrho_pred / self.scaling.invrho_scale
        T_scaled = (T - Tref) / 100.0
        cp_in = torch.cat([
            h,
            T_scaled[:, None],
            theta[:, None],
            theta_powers,
            rho_scaled[:, None],
            invrho_scaled[:, None],
        ], dim=1)
        # No density-coupled Cp prior:
        # Cp is predicted directly from the shared representation, temperature,
        # and density-derived features, scaled around the training-set Cp mean.
        cp_scaled = self.cp_head(cp_in).squeeze(1)
        cp_pred = self.scaling.cp_mean + self.scaling.cp_std * cp_scaled

        return {
            "rho_pred": rho_pred,
            "invrho_pred": invrho_pred,
            "logeta_pred": logeta_pred,
            "cp_pred": cp_pred,
            "density_coeff_scaled": dcoef,
            "eta_coeff_scaled": ecoef,
        }



class CleanPhysicsLossWrapper(nn.Module):
    """
    Clean explicit physics-loss version.

    base_model gives structured predictions:
        rho_struct(T)
        logeta_struct(T)
        cp_struct(T)

    auxiliary free/direct heads give:
        rho_free(T)
        logeta_free(T)

    Training loss uses:
        data loss:    free rho/logeta against data
        physics loss: free rho/logeta against structured rho/logeta

    Cp is trained without the density-coupled Cp prior: Cp_pred = Cp_mean + Cp_std*NN_output.
    Existing screening scripts remain compatible because the saved
    insitu_multitask_nn_no_morgan.pt stores only base_model.
    """
    def __init__(
        self,
        n_features: int,
        degree: int,
        hidden: List[int],
        dropout: float,
        scaling: Scaling,
        cp_prior_params: Dict[str, float],
        rho_mean: float,
    ):
        super().__init__()
        self.base_model = InSituILModel(
            n_features=n_features,
            degree=degree,
            hidden=hidden,
            dropout=dropout,
            scaling=scaling,
            cp_prior_params=cp_prior_params,
        )
        self.scaling = scaling
        self.rho_mean = float(rho_mean)
        last_hidden = hidden[-1] if hidden else n_features

        direct_in_dim = last_hidden + degree + 3
        mid = max(32, last_hidden // 2 if hidden else 64)

        self.rho_free_head = nn.Sequential(
            nn.Linear(direct_in_dim, mid),
            nn.ReLU(),
            nn.Dropout(dropout) if dropout > 0 else nn.Identity(),
            nn.Linear(mid, 1),
        )
        self.logeta_free_head = nn.Sequential(
            nn.Linear(direct_in_dim, mid),
            nn.ReLU(),
            nn.Dropout(dropout) if dropout > 0 else nn.Identity(),
            nn.Linear(mid, 1),
        )
        self._init_free_heads()

    def _init_free_heads(self) -> None:
        for head in [self.rho_free_head, self.logeta_free_head]:
            nn.init.zeros_(head[-1].weight)
            nn.init.zeros_(head[-1].bias)

    def forward(self, X_group: torch.Tensor, group_idx: torch.Tensor, T: torch.Tensor) -> Dict[str, torch.Tensor]:
        out = self.base_model(X_group, group_idx, T)
        h = self.base_model.shared(X_group[group_idx])

        Tref = self.scaling.tref
        T_scaled = (T - Tref) / 100.0
        theta = Tref / torch.clamp(T, min=1.0)
        theta_powers = torch.stack([theta ** k for k in range(1, self.base_model.degree + 1)], dim=1)

        direct_in = torch.cat([
            h,
            T_scaled[:, None],
            theta[:, None],
            theta_powers,
            out["rho_pred"][:, None] / 1000.0,
        ], dim=1)

        rho_free_scaled = self.rho_free_head(direct_in).squeeze(1)
        logeta_free_scaled = self.logeta_free_head(direct_in).squeeze(1)

        out["rho_free_pred"] = self.rho_mean + self.scaling.rho_std * rho_free_scaled
        out["logeta_free_pred"] = self.scaling.logeta_mean + self.scaling.logeta_std * logeta_free_scaled
        return out


def masked_mse(pred: torch.Tensor, true: torch.Tensor, mask: torch.Tensor, scale: float) -> torch.Tensor:
    m = mask > 0.5
    if torch.sum(m) == 0:
        return pred.sum() * 0.0
    err = (pred[m] - true[m]) / scale
    return torch.mean(err * err)


def collect_predictions(model: InSituILModel, X_group_tensor: torch.Tensor, loader: DataLoader, device: torch.device) -> pd.DataFrame:
    model.eval()
    rows = []
    with torch.no_grad():
        for batch in loader:
            group_idx = batch["group_idx"].to(device)
            T = batch["T"].to(device)
            out = model(X_group_tensor, group_idx, T)
            n = len(T)
            for i in range(n):
                rows.append({
                    "group_idx_internal": int(group_idx[i].cpu().item()),
                    "temperature_K": float(T[i].cpu().item()),
                    "density_true_kg_m3": float(batch["rho"][i].item()) if batch["rho_mask"][i].item() > 0.5 else np.nan,
                    "cp_true_JkgK": float(batch["cp"][i].item()) if batch["cp_mask"][i].item() > 0.5 else np.nan,
                    "log10_viscosity_true_mPa_s": float(batch["logeta"][i].item()) if batch["eta_mask"][i].item() > 0.5 else np.nan,
                    "density_pred_kg_m3": float(out["rho_pred"][i].cpu().item()),
                    "cp_pred_JkgK": float(out["cp_pred"][i].cpu().item()),
                    "log10_viscosity_pred_mPa_s": float(out["logeta_pred"][i].cpu().item()),
                    "density_free_pred_kg_m3": float(out["rho_free_pred"][i].cpu().item()) if "rho_free_pred" in out else np.nan,
                    "log10_viscosity_free_pred_mPa_s": float(out["logeta_free_pred"][i].cpu().item()) if "logeta_free_pred" in out else np.nan,
                })
    return pd.DataFrame(rows)


def metric_rows(pred_df: pd.DataFrame, split: str) -> List[Dict[str, float | str | int]]:
    specs = [
        ("density_kg_m3", "density_true_kg_m3", "density_pred_kg_m3", False),
        ("cp_JkgK", "cp_true_JkgK", "cp_pred_JkgK", False),
        ("log10_viscosity_mPa_s", "log10_viscosity_true_mPa_s", "log10_viscosity_pred_mPa_s", True),
    ]
    rows = []
    for target, true_col, pred_col, is_logeta in specs:
        yt = pd.to_numeric(pred_df[true_col], errors="coerce").to_numpy(float)
        yp = pd.to_numeric(pred_df[pred_col], errors="coerce").to_numpy(float)
        m = np.isfinite(yt) & np.isfinite(yp)
        if m.sum() == 0:
            continue
        rmse = math.sqrt(mean_squared_error(yt[m], yp[m]))
        mae = mean_absolute_error(yt[m], yp[m])
        rows.append({
            "split": split,
            "target": target,
            "n": int(m.sum()),
            "r2": float(r2_score(yt[m], yp[m])) if m.sum() > 1 else np.nan,
            "mae": float(mae),
            "rmse": float(rmse),
            "factor_error_rmse": float(10 ** rmse) if is_logeta else np.nan,
        })
    return rows


def parse_hidden(s: str) -> List[int]:
    return [int(x.strip()) for x in s.split(",") if x.strip()]


def set_seed(seed: int) -> None:
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    torch.cuda.manual_seed_all(seed)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--input", required=True, help="Pointwise cleaned pure/binary IL CSV.")
    ap.add_argument("--output_dir", default="insitu_nn_no_morgan_results")
