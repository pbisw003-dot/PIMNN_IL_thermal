#!/usr/bin/env python3
r"""
Train in-situ PyTorch multitarget NN using an optional predicted phase-transition feature.

Default phase use:
    group-level extra feature = pred_phase_transition_K only.

For physics-filtered training, pass the filtered CSV generated by:
    add_phase_transition_predictions_and_filter_property_dataset.py

In-situ PyTorch multi-task model for IL density, Cp, and viscosity.

This script DOES NOT first create per-group fitted viscosity/density parameters.
Instead, the neural network predicts group-level curve coefficients from
RDKit/composition descriptors, reconstructs properties at each pointwise
measurement temperature inside the forward pass, and trains directly against
pointwise data.

Architecture:
    group descriptors -> shared MLP ->
        density head: v0, v1 for linear specific volume
            1/rho(T) = v0 + v1*(T - Tref)

        viscosity head: inverse-temperature Taylor/VFT-polynomial coefficients
            log10(eta) = A + b1*(Tref/T) + ... + bd*(Tref/T)^d

        Cp residual head:
            Cp_prior = Ridge([1/rho_pred]) using the same Cp prior form as before
            Cp = Cp_prior + residual_NN(descriptors, T, rho_pred)

No Morgan fingerprints are used. N_BITS is fixed internally to 0.

Example:
    python .\train_insitu_multitask_nn_no_morgan.py --input .\strict_same_condition_training_all.csv --output_dir .\insitu_nn_no_morgan_results --degree 4 --epochs 1000 --patience 100
"""

