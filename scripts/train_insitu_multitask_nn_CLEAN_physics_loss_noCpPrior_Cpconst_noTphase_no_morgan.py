def morgan_count_fp(smiles: object, n_bits: int = N_BITS, radius: int = 2) -> np.ndarray:
    # Morgan fingerprints are intentionally disabled in this workflow.
    if n_bits <= 0:
        return np.zeros(0, dtype=float)

    mol = mol_from_smiles(smiles)
    arr = np.zeros(n_bits, dtype=float)
    if mol is None:
        arr[:] = np.nan
        return arr
    try:
        fp = AllChem.GetHashedMorganFingerprint(mol, radius=radius, nBits=n_bits)
        for bit, val in fp.GetNonzeroElements().items():
            arr[int(bit) % n_bits] = float(val)
    except Exception:
        arr[:] = np.nan
    return arr


def split_dot_smiles(smiles: object) -> Tuple[str, str, str]:
    """Return (anion, cation, status). Only uses formal charge, no repair."""
    s = norm_text(smiles)
    if not s or "." not in s:
        return "", "", "no_dot_or_blank"
    frags = [f.strip() for f in s.split(".") if f.strip()]
    if len(frags) != 2:
        return "", "", "not_two_fragments"
    mols = [mol_from_smiles(f) for f in frags]
    if any(m is None for m in mols):
        return "", "", "parse_failed"
    charges = [formal_charge(m) for m in mols]
    if sorted(charges) != [-1.0, 1.0]:
        return "", "", f"bad_charges_{charges}"
    anion = frags[int(np.argmin(charges))]
    cation = frags[int(np.argmax(charges))]
    return anion, cation, "ok"


def get_smiles_columns(df: pd.DataFrame) -> Dict[str, Optional[str]]:
    return {
        "IL1_smiles": first_existing(df, ["IL1_smiles", "il1_smiles", "component_1_smiles", "component_1_SMILES"]),
        "IL1_anion_smiles": first_existing(df, ["IL1_anion_smiles", "il1_anion_smiles", "component_1_anion_smiles"]),
        "IL1_cation_smiles": first_existing(df, ["IL1_cation_smiles", "il1_cation_smiles", "component_1_cation_smiles"]),
        "IL2_smiles": first_existing(df, ["IL2_smiles", "il2_smiles", "component_2_smiles", "component_2_SMILES"]),
        "IL2_anion_smiles": first_existing(df, ["IL2_anion_smiles", "il2_anion_smiles", "component_2_anion_smiles"]),
        "IL2_cation_smiles": first_existing(df, ["IL2_cation_smiles", "il2_cation_smiles", "component_2_cation_smiles"]),
    }


def ensure_ion_smiles(df: pd.DataFrame) -> pd.DataFrame:
    """Ensure IL1/IL2 whole/cation/anion SMILES columns exist in standardized names."""
    df = df.copy()
    cols = get_smiles_columns(df)

    for std, col in cols.items():
        if col is not None and col != std:
            df[std] = df[col]
        elif col is None and std not in df.columns:
            df[std] = ""

    for prefix in ["IL1", "IL2"]:
        whole = f"{prefix}_smiles"
        anion = f"{prefix}_anion_smiles"
        cation = f"{prefix}_cation_smiles"
        if whole not in df.columns:
            df[whole] = ""
        if anion not in df.columns:
            df[anion] = ""
        if cation not in df.columns:
            df[cation] = ""

        # Fill cation/anion from whole dot SMILES where missing.
        new_anions = []
        new_cations = []
        for old_a, old_c, smi in zip(df[anion], df[cation], df[whole]):
            a = norm_text(old_a)
            c = norm_text(old_c)
            if a and c:
                new_anions.append(a)
                new_cations.append(c)
            else:
                aa, cc, status = split_dot_smiles(smi)
                new_anions.append(a or aa)
                new_cations.append(c or cc)
        df[anion] = new_anions
        df[cation] = new_cations

    return df


def likely_binary_row(row: pd.Series) -> bool:
    x2 = row.get("x2", 0.0)
    il2 = norm_text(row.get("IL2_smiles", "")) or norm_text(row.get("IL2_cation_smiles", "")) or norm_text(row.get("IL2_anion_smiles", ""))
    try:
        return bool(np.isfinite(float(x2)) and float(x2) > 1e-8 and il2)
    except Exception:
        return bool(il2)


def descriptors_for_il(cation: object, anion: object, whole: object, n_bits: int = N_BITS) -> Tuple[Dict[str, float], np.ndarray]:
    cat = rdkit_scalar_descriptors(cation)
    an = rdkit_scalar_descriptors(anion)
    whole_desc = rdkit_scalar_descriptors(whole if norm_text(whole) else f"{norm_text(anion)}.{norm_text(cation)}")

    out: Dict[str, float] = {}
    for k, v in cat.items():
        out[f"cat_{k}"] = v
    for k, v in an.items():
        out[f"an_{k}"] = v
    for k, v in whole_desc.items():
        out[f"whole_{k}"] = v

    cat_fp = morgan_count_fp(cation, n_bits=n_bits)
    an_fp = morgan_count_fp(anion, n_bits=n_bits)
    fp = np.concatenate([cat_fp, an_fp])
    return out, fp


def il_key(row: pd.Series, prefix: str) -> str:
    whole = norm_text(row.get(f"{prefix}_smiles", ""))
    if whole:
        return whole
    an = norm_text(row.get(f"{prefix}_anion_smiles", ""))
    cat = norm_text(row.get(f"{prefix}_cation_smiles", ""))
    return f"{an}.{cat}" if an or cat else ""


def canonical_group(row: pd.Series, x_round: int = 6) -> Dict[str, object]:
    """Canonicalize pure/binary groups including composition.

    For binaries, the two ILs are sorted by their SMILES key, and x_canonical
    is always the mole fraction of the first sorted IL. Therefore label-swapped
    rows map to the same group.
    """
    il1_key = il_key(row, "IL1")
    il2_key = il_key(row, "IL2")
    x1 = row.get("x1", 1.0)
    x2 = row.get("x2", 0.0)
    try:
        x1f = float(x1) if pd.notna(x1) else 1.0
    except Exception:
        x1f = 1.0
    try:
        x2f = float(x2) if pd.notna(x2) else 0.0
    except Exception:
        x2f = 0.0

    # Treat x=0 or x=1 endpoints as pure if one component is absent/negligible.
    if (not il2_key) or x2f <= 1e-8:
        return {
            "group_id": f"pure::{il1_key}",
            "is_binary_canonical": 0,
            "IL_A_key": il1_key,
            "IL_B_key": "",
            "x_A": 1.0,
            "x_B": 0.0,
            "source_order_swapped": 0,
        }
    if x1f <= 1e-8:
        return {
            "group_id": f"pure::{il2_key}",
            "is_binary_canonical": 0,
            "IL_A_key": il2_key,
            "IL_B_key": "",
            "x_A": 1.0,
            "x_B": 0.0,
            "source_order_swapped": 0,
        }

    if il1_key <= il2_key:
        A_key, B_key = il1_key, il2_key
        xA, xB = x1f, x2f
        swapped = 0
    else:
        A_key, B_key = il2_key, il1_key
        xA, xB = x2f, x1f
        swapped = 1

    xr = round(float(xA), x_round)
    group_id = f"binary::{A_key}||{B_key}::xA={xr:.{x_round}f}"
    return {
        "group_id": group_id,
        "is_binary_canonical": 1,
        "IL_A_key": A_key,
        "IL_B_key": B_key,
        "x_A": float(xA),
        "x_B": float(xB),
        "source_order_swapped": swapped,
    }


def build_group_feature_table(point_df: pd.DataFrame) -> Tuple[pd.DataFrame, pd.DataFrame]:
    """Return (point_df_with_group_meta, group_feature_df)."""
    df = ensure_ion_smiles(point_df)
    meta = df.apply(canonical_group, axis=1, result_type="expand")
    df = pd.concat([df.reset_index(drop=True), meta.reset_index(drop=True)], axis=1)

    # Build a lookup from whole IL key to cation/anion/whole SMILES. First nonempty wins.
    il_lookup: Dict[str, Dict[str, str]] = {}
    for _, row in df.iterrows():
        for prefix in ["IL1", "IL2"]:
            key = il_key(row, prefix)
            if not key:
                continue
            if key not in il_lookup:
                il_lookup[key] = {
                    "whole": norm_text(row.get(f"{prefix}_smiles", "")),
                    "anion": norm_text(row.get(f"{prefix}_anion_smiles", "")),
                    "cation": norm_text(row.get(f"{prefix}_cation_smiles", "")),
                }

    cache_desc: Dict[str, Dict[str, float]] = {}

    def desc_for_key(key: str) -> Dict[str, float]:
        if not key:
            return {}
        if key not in cache_desc:
            rec = il_lookup.get(key, {})
            d, _fp = descriptors_for_il(rec.get("cation", ""), rec.get("anion", ""), rec.get("whole", key), n_bits=N_BITS)
            cache_desc[key] = d
        return cache_desc[key]

    group_rows: List[Dict[str, float | str | int]] = []
    for gid, g in df.groupby("group_id", sort=False):
        row0 = g.iloc[0]
        A_key = norm_text(row0["IL_A_key"])
        B_key = norm_text(row0["IL_B_key"])
        xA = float(row0["x_A"])
        xB = float(row0["x_B"])
        is_binary = int(row0["is_binary_canonical"])

        dA = desc_for_key(A_key)
        dB = desc_for_key(B_key) if B_key else {k: 0.0 for k in dA.keys()}

        out: Dict[str, float | str | int] = {
            "group_id": gid,
            "is_binary_canonical": is_binary,
            "IL_A_key": A_key,
            "IL_B_key": B_key,
            "x_A": xA,
            "x_B": xB,
            "x_A_x_B": xA * xB,
        }
        keys = sorted(set(dA.keys()).union(dB.keys()))
        for k in keys:
            vA = float(dA.get(k, np.nan))
            vB = float(dB.get(k, 0.0 if not B_key else np.nan))
            if not np.isfinite(vB) and xB == 0:
                vB = 0.0
            out[f"IL_A_{k}"] = vA
            out[f"IL_B_{k}"] = vB
            out[f"mix_{k}"] = xA * vA + xB * vB if np.isfinite(vA) and np.isfinite(vB) else np.nan
            out[f"diff_{k}"] = abs(vA - vB) if np.isfinite(vA) and np.isfinite(vB) else np.nan
            out[f"interaction_{k}"] = xA * xB * abs(vA - vB) if np.isfinite(vA) and np.isfinite(vB) else np.nan
        group_rows.append(out)

    group_df = pd.DataFrame(group_rows)
    return df, group_df


def fit_cp_prior(train_df: pd.DataFrame) -> Tuple[Pipeline, Dict[str, float]]:
    cp = pd.to_numeric(train_df.get("cp_JkgK"), errors="coerce").to_numpy(float)
    rho = pd.to_numeric(train_df.get("density_kg_m3"), errors="coerce").to_numpy(float)
    mask = np.isfinite(cp) & np.isfinite(rho) & (rho > 0)
    if mask.sum() < 5:
        raise ValueError("Not enough training rows with both Cp and density to fit Cp prior.")
    X = pd.DataFrame({"inv_density": 1.0 / rho[mask]})
    y = cp[mask]
    pipe = Pipeline([
        ("imputer", SimpleImputer(strategy="median")),
        ("scaler", StandardScaler()),
        ("ridge", Ridge(alpha=1.0)),
    ])
    pipe.fit(X, y)

    scaler = pipe.named_steps["scaler"]
    ridge = pipe.named_steps["ridge"]
    params = {
        "ridge_intercept": float(ridge.intercept_),
        "ridge_coef_scaled_inv_density": float(ridge.coef_[0]),
        "scaler_mean_inv_density": float(scaler.mean_[0]),
        "scaler_scale_inv_density": float(scaler.scale_[0]) if float(scaler.scale_[0]) != 0 else 1.0,
        "n_cp_prior_train": int(mask.sum()),
    }
    return pipe, params


def cp_prior_from_params(inv_density: torch.Tensor, params: Dict[str, float]) -> torch.Tensor:
    z = (inv_density - params["scaler_mean_inv_density"]) / params["scaler_scale_inv_density"]
    return params["ridge_intercept"] + params["ridge_coef_scaled_inv_density"] * z


